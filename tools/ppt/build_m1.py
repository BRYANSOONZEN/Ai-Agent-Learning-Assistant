def caption(s, x, y, w, txt, size=9, color=GREY):
    """原生坐标（英寸）的一行小字说明"""
    sp = s.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(0.3))
    tf = sp.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    r = tf.paragraphs[0].add_run()
    r.text = txt
    set_font(r, size, color)
    return sp


def frow(s, x, y, n, expr, note, size=17):
    """一行公式：编号 + 公式图 + 右边一句符号说明；返回下一行的 y"""
    caption(s, x, y + 0.02, 0.3, n, 11, INK)
    pic, w, h = place(s, expr, x + 0.3, y, size=size)
    nx = x + 0.35 + w + 0.15
    caption(s, nx, y + max(0, h / 2 - 0.1), max(1.5, 9.5 - nx), note)
    return y + h + 0.16


